public class ContohVariable26 {
    public static void main(String[] args) {
        String hobiSaya = "Bermain Sepak Bola";
        boolean isPandai = true;
        char jenisKelamin = 'L';
        byte umurSayaSekarang = 20;
        double ipk = 3.24;
        double tinggi = 1.78;

        System.out.println(hobiSaya);
        System.out.println("Apakah pandai? " + isPandai);
        System.out.println("Jenis kelamin: " + jenisKelamin);
        System.out.println("Umurku saat ini: " + umurSayaSekarang);
        System.out.printf("Saya beripk %.2f, dengan tinggi badan %.2f%n", ipk, tinggi);
    }
}